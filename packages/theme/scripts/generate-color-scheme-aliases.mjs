/**
 * Generates `src/color-scheme-aliases.css.ts` from the installed `@equinor/eds-tokens`.
 *
 * EDS declares semantic colour aliases (for example
 * `--eds-color-bg-accent-fill-emphasis-default: var(--eds-color-accent-9)`) only on
 * `:root, [data-color-scheme="light"]`. A `[data-color-scheme="dark"]` subtree therefore
 * inherits aliases already resolved to light values. `<fwc-theme>` re-declares the aliases
 * on its host so they resolve against the colour scheme applied to the host.
 *
 * Run with `pnpm --filter @equinor/fusion-wc-theme generate:color-scheme` after upgrading
 * `@equinor/eds-tokens`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = join(dirname(require.resolve('@equinor/eds-tokens/css/variables')), '../..');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const source = readFileSync(join(pkgDir, 'build/css/variables.css'), 'utf8');

const selector = ':root, [data-color-scheme="light"] {';
const declarations = [];
let index = source.indexOf(selector);
while (index !== -1) {
  const body = source.slice(index + selector.length, source.indexOf('}', index));
  for (const line of body.split('\n')) {
    const match = line.trim().match(/^(--eds-color-[\w-]+):\s*(var\(--eds-color-[\w-]+\));$/);
    if (match) declarations.push(`    ${match[1]}: ${match[2]};`);
  }
  index = source.indexOf(selector, index + selector.length);
}

if (declarations.length === 0) {
  throw new Error('No EDS colour aliases found; check the @equinor/eds-tokens CSS format.');
}

const output = `// Generated by scripts/generate-color-scheme-aliases.mjs from @equinor/eds-tokens@${version}. Do not edit.
import { css, type CSSResult } from 'lit';

/** EDS semantic colour aliases, re-declared so they resolve against the host colour scheme. */
export const colorSchemeAliases: CSSResult = css\`
  :host {
${declarations.join('\n')}
  }
\`;

export default colorSchemeAliases;
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/color-scheme-aliases.css.ts');
writeFileSync(target, output);
console.log(`Wrote ${declarations.length} aliases from @equinor/eds-tokens@${version}`);
